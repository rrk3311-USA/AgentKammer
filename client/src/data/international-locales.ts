export function resolveLocaleKey(languageCode: string): string {
  const code = languageCode.trim();
  if (code === "zh-CN") return "zh-CN";
  if (code === "zh-HK" || code === "zh-TW") return "zh-TW";
  if (code === "de" || code === "de-CH") return "de";
  if (code === "es" || code === "es-MX" || code === "es-AR" || code === "es-CO" || code === "es-CL") return "es";
  if (code === "pt-BR") return "pt-BR";
  if (code === "pt-PT") return "pt";
  if (
    code === "en" ||
    code.startsWith("en-") ||
    code === "en-SG" ||
    code === "en-GB" ||
    code === "en-IE" ||
    code === "en-CA" ||
    code === "en-AU" ||
    code === "en-NZ" ||
    code === "en-IN"
  ) {
    return "en";
  }
  const direct = [
    "fr",
    "it",
    "nl",
    "ko",
    "ja",
    "sv",
    "nb",
    "da",
    "fi",
    "pl",
    "cs",
    "ro",
    "hu",
    "el",
    "ru",
    "uk",
    "tr",
    "ar",
    "he",
    "vi",
    "th",
    "id",
    "ms",
  ];
  if (direct.includes(code)) return code;
  return "en";
}

export function applyLocaleTemplate(template: string, country: string, language: string): string {
  return template.replaceAll("{country}", country).replaceAll("{language}", language);
}

